#!/usr/bin/env node
/**
 * dsh-run — the Kestra AIAgent container entry (dsh.docx 第二种运行位置).
 *
 * Translates the AIAgent environment contract into one headless dsh
 * invocation. The dsh.patch.yml insert row names this package as a bare
 * specifier, which resolves from the PROFILE directory — a workspace package
 * outside apps/cli's dependency closure can't resolve that way, so this entry
 * writes a generated overlay that names the plugin module by ABSOLUTE file URL
 * (env-driven config included), then boots:
 *
 *   dsh --profile headless --patch <generated-overlay> "<DSH_PROMPT>"
 *
 * The generated overlay and the committed dsh.patch.yml carry the same rows;
 * keep both in sync (the bundle file is for the published-package path).
 *
 * The launcher resolves in order: workspace source mode (this package lives in
 * a dsh checkout — run apps/cli/src/bin.ts directly, bypassing pnpm's
 * pre-run workspace verification which needs registry access), then `pnpm dsh`,
 * then a `dsh` binary on PATH.
 *
 * Exit codes: 0 completed · 1 run failed · 2 usage · 124 DSH_TIMEOUT expiry
 * (the overlay's observer requests 124 itself; this script passes it through).
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'

const prompt = process.env.DSH_PROMPT ?? ''
if (prompt.trim() === '') {
  console.error('dsh-run: DSH_PROMPT is required')
  process.exit(2)
}

/** Absolute file URL of this package's plugin module (lib/index.js). */
const packageDir = fileURLToPath(new URL('..', import.meta.url))
const pluginModuleUrl = pathToFileURL(join(packageDir, 'lib', 'index.js')).href

// NOTE: single-line !!js expressions — the YAML parser rejects multi-line scalars here.
const overlay = [
  '# Generated by bin/dsh-run.mjs — env-driven Kestra AIAgent execution overlay.',
  '- id: agent-default-model',
  '  config:',
  "    provider: !!js process.env.DSH_PROVIDER || 'deepseek-official'",
  "    model: !!js process.env.DSH_MODEL || 'deepseek-v4-flash'",
  '',
  '- insert:',
  '    - id: kestra-run',
  `      name: '${pluginModuleUrl}'`,
  '      config:',
  "        resultFile: !!js (process.env.DSH_OUTPUT_FILE || '/result.json')",
  '        allowTools: !!js ((process.env.DSH_TOOLS && process.env.DSH_TOOLS.split(\',\').map(s => s.trim()).filter(Boolean)) || undefined)',
  '        maxIterations: !!js (Number(process.env.DSH_MAX_ITERATIONS) || 0)',
  '        timeoutSeconds: !!js (Number(process.env.DSH_TIMEOUT) || 0)',
  '',
].join('\n')

const tempDir = mkdtempSync(join(tmpdir(), 'dsh-run-'))
const overlayPath = join(tempDir, 'dsh-run.overlay.yml')
writeFileSync(overlayPath, overlay)

const args = ['--profile', 'headless', '--patch', overlayPath, prompt, ...process.argv.slice(2)]

/** Walk up from this package to the workspace root that carries apps/cli. */
function workspaceRoot(startDir) {
  let dir = resolve(startDir)
  for (; ; dir = dirname(dir)) {
    if (existsSync(join(dir, 'apps', 'cli', 'src', 'bin.ts'))) return dir
    const parent = dirname(dir)
    if (parent === dir) return undefined
  }
}

const root = workspaceRoot(packageDir)
let result
if (root !== undefined) {
  result = spawnSync(process.execPath,
    ['--import', 'tsx/esm', join(root, 'apps', 'cli', 'src', 'bin.ts'), ...args],
    { stdio: 'inherit', env: process.env, cwd: root })
} else {
  result = spawnSync('pnpm', ['dsh', ...args], { stdio: 'inherit', env: process.env })
  if (result.error?.code === 'ENOENT') {
    result = spawnSync('dsh', args, { stdio: 'inherit', env: process.env })
  }
}
process.exit(result.status ?? 1)
